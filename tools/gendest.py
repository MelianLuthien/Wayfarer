"""Generate src/destinations.h from Hookshot's destination table (host/hos_main.c, GPL-3.0).

usage: python tools/gendest.py "<path to hos_main.c>"
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("oot_destinations[] = {")
end = src.index("\n};", start)
region = src[start:end]
entries = re.findall(r'\{((?:"[^"]*"|NULL|,|\s)+)\},\s*/\* (.*?) \*/', region)
names, strs = [], []
for body, name in entries:
    parts = [p.strip() for p in body.split(",") if p.strip()]
    assert len(parts) == 6, (name, parts)
    names.append(name)
    strs += ["" if p == "NULL" else p.strip('"') for p in parts]
assert len(names) == 31, len(names)

def blob(items, indent="    "):
    return "\n".join('%s"%s%s"' % (indent, s, chr(92) + "0") for s in items)

out = ["/* Generated by tools/gendest.py from Hookshot's host/hos_main.c (GPL-3.0). Do not edit. */",
       "#define TP_COUNT %d" % len(names),
       "/* Names, then per destination six strings: child map, start, boot event, adult map, start, boot event ",
       "   (empty when the place does not exist for that age). */",
       "static const char tp_names[] =", blob(names) + ";",
       "static const char tp_dest[] =", blob(strs) + ";", ""]
open(os.path.join(ROOT, "src", "destinations.h"), "w", newline="\n").write("\n".join(out))
print("wrote src/destinations.h:", len(names), "places")
