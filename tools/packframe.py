"""Build the menu's background (carved frame and parchment) into build/art/panel.bin and src/panel.h.

usage: python tools/packframe.py

The blob is plain RGB, 1080 x 680 (twice the 540 x 340 logical panel), 3 bytes a pixel, no header.
The frame is cut from the owner's art (build/art/full/frame_corner.png and frame_edge.png), put
together with the corner's arms fading into the edge strips, over a procedural parchment.
The overlay is copied to the screen as a plain rectangle, so what lies outside the carved shape
is filled with dark wood here instead of being transparent.
Without the art (fresh checkout) a flat parchment with a plain brown border is written instead.
"""
import os
import random

import numpy as np
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "build", "art")
W, H = 1080, 680
K = 0.34                 # art scale: the 416 px corner becomes about 141 px, 71 at logical size
OV = 32                  # the arms fade into the edge strips over this many pixels
M = 56                   # parchment inset (28 logical px)
OUTSIDE = (22, 15, 10)
random.seed(7)


def despill(im):
    a = np.array(im).astype(float)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    m = (r - g > 14) & (b - g > 8) & (a[..., 3] > 0)
    a[..., 0] = np.where(m, np.minimum(r, g * 1.12), r)
    a[..., 2] = np.where(m, np.minimum(b, g * 0.7), b)
    return Image.fromarray(a.astype(np.uint8))


def resize(im, w, h):
    return im.resize((max(1, round(w)), max(1, round(h))), Image.LANCZOS)


def parchment():
    def noise(s):
        n = Image.new("L", (W // s + 2, H // s + 2))
        n.putdata([random.randint(0, 255) for _ in range((W // s + 2) * (H // s + 2))])
        return n.resize((W, H), Image.BICUBIC)
    a = np.zeros((H, W, 3), np.float32) + np.array([214, 183, 130], np.float32)
    for n, amt in ((noise(80), .07), (noise(20), .04), (noise(2), .03)):
        a += ((np.array(n, np.float32) - 128) * amt)[..., None] * np.array([1, .95, .8], np.float32)
    yy, xx = np.mgrid[0:H, 0:W]
    d = np.sqrt(((xx - W / 2) / (W / 2)) ** 2 + ((yy - H / 2) / (H / 2)) ** 2)
    a *= (1 - 0.12 * np.clip(d - 0.5, 0, 1))[..., None]
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8)).convert("RGBA")


def frame():
    fc, fe = os.path.join(ART, "full", "frame_corner.png"), os.path.join(ART, "full", "frame_edge.png")
    fr = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    if not (os.path.exists(fc) and os.path.exists(fe)):
        fr.paste((120, 88, 52, 255), (0, 0, W, H))
        fr.paste((0, 0, 0, 0), (M // 2, M // 2, W - M // 2, H - M // 2))
        return fr, False
    c, e = despill(Image.open(fc).convert("RGBA")), despill(Image.open(fe).convert("RGBA"))
    cs = resize(c, 416 * K, 411 * K)
    arr = np.array(cs).astype(float)
    ramp = np.linspace(1, 0, OV)
    arr[:, -OV:, 3] *= ramp[None, :]
    arr[-OV:, :, 3] *= ramp[:, None]
    cs = Image.fromarray(arr.astype(np.uint8))
    tw = W - 2 * cs.width + 2 * OV
    top = resize(e, tw, 186 * K)
    ty = round(34 * K)
    fr.alpha_composite(top, (cs.width - OV, ty))
    fr.alpha_composite(ImageOps.flip(top), (cs.width - OV, H - ty - top.height))
    lw, lh = round(201 * K), H - 2 * cs.height + 2 * OV
    left = resize(c.crop((23, 330, 224, 411)), lw, lh)
    lx = round(23 * K)
    fr.alpha_composite(left, (lx, cs.height - OV))
    fr.alpha_composite(ImageOps.mirror(left), (W - lx - lw, cs.height - OV))
    fr.alpha_composite(cs, (0, 0))
    fr.alpha_composite(ImageOps.mirror(cs), (W - cs.width, 0))
    fr.alpha_composite(ImageOps.flip(cs), (0, H - cs.height))
    fr.alpha_composite(ImageOps.flip(ImageOps.mirror(cs)), (W - cs.width, H - cs.height))
    return fr, True


fr, have = frame()
panel = Image.new("RGBA", (W, H), OUTSIDE + (255,))
mask = Image.new("L", (W, H), 0)
mask.paste(255, (M, M, W - M, H - M))
panel.paste(parchment(), (0, 0), mask)
panel.alpha_composite(fr)
os.makedirs(ART, exist_ok=True)
open(os.path.join(ART, "panel.bin"), "wb").write(panel.convert("RGB").tobytes())
hdr = ["/* Generated by tools/packframe.py. Do not edit. */", "#define PANEL_SRC_W %d" % W, "#define PANEL_SRC_H %d" % H]
open(os.path.join(ROOT, "src", "panel.h"), "w", newline=chr(10)).write(chr(10).join(hdr) + chr(10))
print("panel %dx%d, art %s" % (W, H, "used" if have else "missing, flat fallback"))
