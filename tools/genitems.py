"""Generate src/items.h from Hookshot's inventory list (GPL-3.0).

usage: python tools/genitems.py <path to oot_cheat_items.h>
"""
import re
import sys

BS0 = chr(92) + "0"
src = open(sys.argv[1], encoding="utf-8").read()
items = re.findall(r'OOT_ITEM\("([^"]+)", "([^"]+)", (\d)\)', src)
assert len(items) == 85, len(items)
# Player-facing names (Hookshot's own names differ): renames, and "Song: " in front of every song.
RENAME = {"Magic Meter": "Gift of Improved Spin", "Double Magic": "Gift of Doubled Magic",
          "Double Defense": "Gift of Halved Damage", "Stone of Agony": "Echo Gem", "Gerudo's Card": "Gerudo Pass"}
SONGS = ["Zelda's Lullaby", "Epona's Song", "Saria's Song", "Sun's Song", "Song of Time", "Song of Storms",
         "Minuet of Forest", "Bolero of Fire", "Serenade of Water", "Nocturne of Shadow", "Requiem of Spirit",
         "Prelude of Light"]
items = [(("Song: " + l) if l in SONGS and not l.startswith("Song of") else RENAME.get(l, l), n, k) for l, n, k in items]
qty = [i for i, (_, _, k) in enumerate(items) if k == "1"]
out = ["/* Generated by tools/genitems.py from Hookshot's inventory list (GPL-3.0). Do not edit. */",
       "#define ITEM_COUNT %d" % len(items),
       "/* Items with a quantity (the rest are owned or not): " + ",".join(map(str, qty)) + " */",
       "#define ITEM_IS_QTY(i) (" + " || ".join("(i) == %d" % k for k in qty) + ")",
       "static const char item_labels[] ="]
out += ['    "%s%s"' % (l, BS0) for l, _, _ in items] + ["    ;", "static const char item_pouch[] ="]
out += ['    "%s%s"' % (n, BS0) for _, n, _ in items] + ["    ;"]
open("src/items.h", "w", newline="\n").write("\n".join(out) + "\n")
