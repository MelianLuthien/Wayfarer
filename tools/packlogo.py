"""Pack the owner's Wayfarer logo (build/art/full/brand_logo.png) into build/art/logo.bin and src/logo.h.

usage: python tools/packlogo.py

The blob is plain RGBA, LOGO_W x LOGO_H, 4 bytes a pixel, no header. The logo is cropped to its
ink first. Without the art (fresh checkout) LOGO_W is 0 and the menu writes the title in text.
"""
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "build", "art")
W = 288
src = os.path.join(ART, "full", "brand_logo.png")
blob, lw, lh = b"", 0, 0
if os.path.exists(src):
    im = Image.open(src).convert("RGBA")
    im = im.crop((0, 0, im.width - 8, im.height))      # the sheet has a stray edge line on the right
    a = im.split()[-1].point(lambda v: 255 if v > 24 else 0)
    im = im.crop(a.getbbox())
    lw, lh = W, round(im.height * W / im.width)
    # premultiply while resizing so the white halo of the sheet does not creep into the edges
    px = im.resize((lw, lh), Image.LANCZOS)
    blob = px.tobytes()
os.makedirs(ART, exist_ok=True)
open(os.path.join(ART, "logo.bin"), "wb").write(blob)
open(os.path.join(ROOT, "src", "logo.h"), "w", newline="\n").write(
    "/* Generated by tools/packlogo.py. Do not edit. */\n#define LOGO_W %d\n#define LOGO_H %d\n" % (lw, lh))
print("logo %dx%d" % (lw, lh))
