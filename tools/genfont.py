"""Render ASCII 32..126 into src/font.h using Pillow's bundled default font
(Aileron Regular, CC0 / public domain), as 8-bit alpha cells with per-glyph advances.

usage: python tools/genfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZE = 14
CW, CH, BASE = 14, 18, 14
font = ImageFont.load_default(size=SIZE)

glyphs, advs = [], []
for c in range(32, 127):
    img = Image.new("L", (CW, CH), 0)
    ImageDraw.Draw(img).text((1, BASE), chr(c), fill=255, font=font, anchor="ls")
    glyphs.append(list(img.tobytes()))
    advs.append(max(1, round(font.getlength(chr(c)))))

lines = [
    "/* Generated by tools/genfont.py: Aileron Regular (CC0), 8-bit alpha. Do not edit. */",
    "#define WF_FONT_W %d" % CW,
    "#define WF_FONT_H %d" % CH,
    "#define WF_FONT_FIRST 32",
    "#define WF_FONT_COUNT %d" % len(glyphs),
    "static const unsigned char wf_font_adv[%d] = {%s};" % (len(advs), ",".join(map(str, advs))),
    "static const unsigned char wf_font[%d][%d] = {" % (len(glyphs), CW * CH),
]
for g in glyphs:
    lines.append("  {" + ",".join(map(str, g)) + "},")
lines.append("};")
open(os.path.join(ROOT, "src", "font.h"), "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote src/font.h", len(glyphs), "glyphs")
