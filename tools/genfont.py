"""Rasterize Cormorant (SIL OFL, see fonts/OFL.txt) into build/art/fonts.bin and src/font.h.

usage: python tools/genfont.py

Three faces, each drawn at 2x its logical size as 8-bit alpha cells with per-glyph advances
(in 2x pixels), so the menu can scale them by 1.5x / 2x / 3x without them going soft:
  face 0  body   Cormorant Garamond, weight 600, 17 px
  face 1  small  Cormorant Garamond, weight 600, 15 px   (descriptions, hints, version)
  face 2  title  Cormorant SC Bold, 16 px
  face 3  tiny   Cormorant Garamond, weight 700, 12 px   (button letters, version)
Glyphs: ASCII 32..126, Latin-1 160..255 and the single angle quotes (U+2039, U+203A).
The blob is the cells of all faces back to back; src/font.h has offsets, sizes, advances.
The cell index of a code point is given by wf_glyph() in src/wayfarer.c.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FD = os.path.join(ROOT, "fonts")
SS = 2
CPS = list(range(32, 127)) + list(range(160, 256)) + [0x2039, 0x203A]

faces = [("CormorantGaramond.ttf", 600, 15), ("CormorantGaramond.ttf", 600, 13), ("CormorantSC-Bold.ttf", None, 14), ("CormorantGaramond.ttf", 700, 11)]
out = ["/* Generated by tools/genfont.py: Cormorant (SIL OFL 1.1), 8-bit alpha at 2x. Do not edit. */",
       "#define WF_FONT_GLYPHS %d" % len(CPS), "#define WF_FONT_SS %d" % SS]
blob = bytearray()
alladv, allbb, dims = [], [], []
for n, (fn, wt, px) in enumerate(faces):
    f = ImageFont.truetype(os.path.join(FD, fn), px * SS)
    if wt is not None:
        f.set_variation_by_axes([wt])
    asc, desc = f.getmetrics()
    cap_h = -f.getbbox("H", anchor="ls")[1]
    pad = 3
    cw = max(int(f.getlength(chr(c)) + 0.999) for c in CPS) + 2 * pad
    ch = asc + desc + 2
    off = len(blob)
    for c in CPS:
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((pad, asc), chr(c), fill=255, font=f, anchor="ls")
        blob += im.tobytes()
        bb = im.getbbox() or (0, 0, 0, 0)
        allbb += list(bb)
        alladv.append(max(1, round(f.getlength(chr(c)))))
    dims.append((cw, ch, pad, asc, cap_h, off))
    print("face", n, "cell", cw, "x", ch, "asc", asc, "cap", cap_h)
# One table per property across all faces (indexed face * GLYPHS + glyph): code never has to pick between arrays.
out.append("static const unsigned char wf_adv[%d] = {%s};" % (len(alladv), ",".join(map(str, alladv))))
out.append("static const unsigned char wf_bb[%d] = {%s};" % (len(allbb), ",".join(map(str, allbb))))
for k, name in enumerate(("w", "h", "pad", "asc", "cap")):
    out.append("static const unsigned char wf_face_%s[%d] = {%s};" % (name, len(faces), ",".join(str(d[k]) for d in dims)))
out.append("static const unsigned int wf_face_off[%d] = {%s};" % (len(faces), ",".join(str(d[5]) for d in dims)))
art = os.path.join(ROOT, "build", "art")
os.makedirs(art, exist_ok=True)
open(os.path.join(art, "fonts.bin"), "wb").write(bytes(blob))
open(os.path.join(ROOT, "src", "font.h"), "w", newline=chr(10)).write(chr(10).join(out) + chr(10))
print("wrote src/font.h and fonts.bin", len(blob), "bytes")
