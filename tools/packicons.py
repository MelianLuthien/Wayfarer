"""Pack the cut icons (build/art/icon128) into one blob for the module and write src/icons.h.

usage: python tools/packicons.py [px]      (default 64)

The blob is plain RGBA, px x px per icon, in manifest order, with no header: icon N starts at
N * px * px * 4. src/icons.h gives every icon its index (ICON_<NAME>) and ICON_COUNT / ICON_PX.
Frame pieces (frame_*, header_*) are not square icons and are left out.
Without art (fresh checkout) an empty blob and ICON_COUNT 0 are written, so the build still works.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "build", "art")
PX = int(sys.argv[1]) if len(sys.argv) > 1 else 64

names, blob = [], bytearray()
mf = os.path.join(ART, "manifest.json")
if os.path.exists(mf):
    for m in json.load(open(mf)):
        n = m["name"]
        if n.startswith(("frame_", "header_")):
            continue
        im = Image.open(os.path.join(ART, "icon128", n + ".png")).convert("RGBA")
        blob += im.resize((PX, PX), Image.LANCZOS).tobytes()
        names.append(n)

os.makedirs(ART, exist_ok=True)
open(os.path.join(ART, "icons%d.bin" % PX), "wb").write(bytes(blob))
lines = ["/* Generated by tools/packicons.py. Do not edit. */",
         "#define ICON_COUNT %d" % len(names), "#define ICON_PX %d" % PX]
lines += ["#define ICON_%s %d" % (n.upper(), i) for i, n in enumerate(names)]
open(os.path.join(ROOT, "src", "icons.h"), "w", newline="\n").write("\n".join(lines) + "\n")
print("packed %d icons at %dx%d: %d bytes" % (len(names), PX, PX, len(blob)))
